package com.kohere.auth.domain;

/**
 * 비밀번호 재설정 링크 발송 남용 방지 포트(Redis 카운터 백킹, US-1-17 · 스펙 §1-8). {@link SignupSmsRateLimiter}·{@link
 * LoginAttemptRateLimiter}와 같은 모양이며 세는 대상만 다르다 — 이쪽은 <b>메일 발송 시도</b>다.
 *
 * <p><b>무엇을 막는 장치인지 정확히 해 둔다.</b> 발송비와 <b>메일 폭탄</b>(남의 메일함을 재설정 메일로 채우는 괴롭힘)을 막는 비용 가드다. 이 경로가 안고
 * 있는 계정 열거 누출(§1-8 — 가입 계정은 SMTP 왕복 시간이 들고 502가 날 수 있어 응답 시간·status로 존재가 샌다)의 <b>완화책이 아니다</b>. 한
 * 주소당 한 번만 재 보면 되는 관찰에는 시간당 5회 한도가 아무 방해가 되지 않는다.
 *
 * <p><b>로그인 시도 버킷({@code web-login:rate:*})을 절대 공유하지 않는다.</b> 공유하면 재설정 요청이 로그인 예산을 깎아, "이메일 한도 = 잠금
 * 임계값의 2배"라는 §1-4의 계약이 깨진다 — 그 계약이 깨지는 순간 <b>잠금이 사실상 도달 불가능</b>해지고(한 시간 창의 예산을 정확히 전부 실패로 써야 상한에
 * 닿는다), 잠금을 검증하던 기존 테스트는 423이 아니라 429를 받고 깨진다. 반대 방향도 나쁘다 — 로그인 실패를 반복한 사용자가 그 때문에 복구 링크조차 받지 못한다.
 *
 * <p>초과 응답은 429 하나이며 어느 축에 걸렸는지 구분해 알리지 않는다(한도 역산 방지).
 */
public interface PasswordResetRateLimiter {

  /**
   * 이번 링크 발송 시도를 카운터에 반영하고, 이메일·IP 어느 한쪽이라도 시간당 한도를 넘겼으면 거절한다.
   *
   * <p><b>계정 조회보다 먼저 부른다.</b> 뒤로 밀면 "가입되지 않은 이메일이라 아무것도 하지 않고 반환"하는 경로가 한도를 <b>세지 않고</b> 지나가, 존재하지
   * 않는 주소로 무제한 두드리며 계정 열거를 할 수 있게 된다. 세는 대상은 "발송된 메일"이 아니라 <b>발송 시도</b>이며, 미가입 이메일도 똑같이 센다.
   *
   * @param email 제출된 이메일. 대소문자를 구분하지 않고 한 버킷으로 묶는다(구현 참조)
   * @param clientIp 호출자 IP(프록시 뒤라면 {@code X-Forwarded-For}의 최좌측 값). 알 수 없으면 {@code null}·공백이며 이때는
   *     이메일 한도만 적용한다
   * @throws PasswordResetRateLimitException 이메일 또는 IP 한도 초과(429 {@code TOO_MANY_REQUESTS})
   */
  void recordAttempt(String email, String clientIp);
}
