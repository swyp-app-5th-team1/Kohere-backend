package com.kohere.auth.domain;

/**
 * 임대인 웹 로그인 시도 레이트리밋 포트(Redis 카운터 백킹, US-1-12). 가입용 SMS의 {@link SignupSmsRateLimiter}와 같은 모양이며 세는
 * 대상만 다르다 — 저쪽은 발송 시도, 이쪽은 <b>로그인 시도</b>다(성공·실패를 가리지 않는다).
 *
 * <p><b>왜 필요한가 — 두 가지다.</b> (1) <b>계정 잠금 DoS 완화</b>: 남의 이메일로 상한만큼 틀리면 그 사람을 잠글 수 있고 해제 경로가 없다. 유저
 * 스토리·시퀀스·결정 브리프가 모두 "IP 레이트리밋으로 완화한다"를 그 대응책으로 적어 두었으므로 실제로 있어야 한다. (2) <b>CPU 증폭 차단</b>: {@code
 * /auth/login}은 <b>아무 선행 조건 없이</b> 인증되지 않은 호출자가 BCrypt 한 라운드를 강제할 수 있는 첫 permitAll 경로다(가입은 SMS 인증
 * 마커라는 게이트 뒤에 있고 그 마커 발급 자체가 이미 레이트리밋된다). 요청 한 번의 비용이 수십 ms라 초당 수십 건이면 코어가 마른다.
 *
 * <p><b>IP와 이메일 두 축을 함께 건다.</b> 이메일 한도만 두면 한 공격자가 이메일을 바꿔가며 CPU를 태우는 것을 못 막고, IP 한도만 두면 분산된 IP에서 한
 * 계정을 잠그는 것을 못 막는다. 다만 둘의 성격은 다르다 — <b>IP 축은 위조 가능하다</b>({@code X-Forwarded-For}는 Caddy가 덧붙일 뿐이라
 * 호출자가 최좌측 값을 스스로 정할 수 있다). 그래서 IP 한도는 <b>비용 가드</b>일 뿐 인가 수단이 아니고, 잠금 DoS를 실제로 제한하는 것은 위조할 수 없는
 * <b>이메일 축</b>이다(잠글 대상을 지정하려면 그 이메일을 보내야만 한다).
 *
 * <p>초과 응답은 429 {@link LoginRateLimitException} 하나다 — 어느 축에 걸렸는지 구분해 알려주면 한도를 역산할 수 있다.
 */
public interface LoginAttemptRateLimiter {

  /**
   * 이번 로그인 시도를 카운터에 반영하고, IP·이메일 어느 한쪽이라도 시간당 한도를 넘겼으면 거절한다.
   *
   * <p><b>반드시 자격증명 조회·BCrypt 대조보다 먼저 부른다.</b> 뒤에서 부르면 이미 해시 비용을 치른 뒤라 (2)의 증폭 표면이 그대로 열려 있고, 한도는
   * "느려지게 하는 장치"가 아니라 "느려진 다음에 붙는 라벨"이 된다.
   *
   * <p>세는 것은 <b>시도</b>이지 실패가 아니다 — 실패만 세면 정답 비밀번호를 섞어 카운터를 우회할 수 있고, 애초에 (2)의 비용은 성공·실패와 무관하게 발생한다.
   *
   * @param email 제출된 로그인 ID(대소문자 구분 없이 한 버킷으로 묶는다 — 구현 참조)
   * @param clientIp 호출자 IP(프록시 뒤라면 {@code X-Forwarded-For}의 최좌측 값). 알 수 없으면 {@code null}·공백이며 이때는
   *     이메일 한도만 적용한다
   * @throws LoginRateLimitException IP 또는 이메일 한도 초과(429)
   */
  void recordAttempt(String email, String clientIp);

  /**
   * 한 이메일의 시도 카운터를 비운다 — <b>비밀번호 재설정 확정</b>의 마지막 단계다(US-1-17).
   *
   * <p><b>왜 필요한가</b> — 잠길 만큼 틀린 사람은 이미 시간당 이메일 한도(잠금 임계값의 2배)의 절반을 태워 둔 상태다. 잠금만 풀고 카운터를 남기면 새
   * 비밀번호를 쥐고 돌아간 로그인 화면에서 429를 맞는다 — 복구를 끝내 놓고 문 앞에서 막는 셈이다. 잠금은 MySQL 컬럼이고 이 카운터는 Redis라, "{@code
   * locked_at}만 비우면 완전한 해제"라는 문서의 단언은 <b>MySQL 쪽 이야기일 뿐</b>이다.
   *
   * <p><b>이메일 축만 지운다.</b> IP 축({@code web-login:rate:ip:*})은 <b>그 IP를 쓰는 모든 호출자가 공유</b>하므로, 재설정 완주로
   * IP 예산이 초기화되면 계정 하나를 가진 공격자가 자기 계정을 재설정하는 것만으로 <b>남의 계정을 향한 시도 예산을 원하는 만큼 되살릴 수 있다</b>. IP 축이
   * 위조로 이미 반쯤 우회되는 비용 가드인 것은 사실이지만, 불완전한 가드에 정식 초기화 버튼을 달아 주는 것은 다른 문제다.
   *
   * <p><b>부르는 시점은 토큰 소비(확정) 뒤여야 한다.</b> 링크 <i>요청</i> 시점에 지우면 남의 이메일로 요청만 넣어도 그 계정의 한도가 초기화되는 우회
   * 오라클이 된다 — 토큰 소유가 곧 메일함 소유 증명이므로 그 증명 뒤에만 비운다.
   *
   * <p>카운터가 이미 없어도(TTL 만료·최초 로그인) 실패하지 않는 멱등 삭제다.
   *
   * @param email 대상 로그인 ID. {@link #recordAttempt}와 <b>같은 규칙으로</b> 접어야 같은 키를 지운다(구현 참조)
   */
  void clearEmailCounter(String email);
}
